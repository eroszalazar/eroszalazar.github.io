(function () {
  const desktopLang = document.getElementById('langToggle');
  const mobileLang  = document.getElementById('langToggleMobile');
  if (!desktopLang || !mobileLang) return;

  // inicializamos el texto del botón móvil igual al de desktop
  mobileLang.textContent = desktopLang.textContent;

  // cuando toco el botón móvil, disparo el click del de desktop
  mobileLang.addEventListener('click', () => {
    desktopLang.click(); // esto llama a onLangChanged como siempre

    // después de que onLangChanged actualice el texto,
    // copiamos el label al botón móvil
    setTimeout(() => {
      mobileLang.textContent = desktopLang.textContent;
    }, 0);
  });
})();



