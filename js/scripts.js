// Aplica traducciones a nodos con data-i18n / data-i18n-html / data-i18n-attr
function applyI18N(lang){
  const dict = I18N[lang] || I18N.es;

  // Texto simple
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const key = el.getAttribute('data-i18n');
    const attrs = el.getAttribute('data-i18n-attr');
    const htmlKey = el.getAttribute('data-i18n-html');

    if (htmlKey) return; // lo procesa el bloque siguiente

    if (attrs) {
      // uno o varios atributos: placeholder, aria-label, content, etc.
      attrs.split(',').map(a=>a.trim()).forEach(attr=>{
        if (dict[key] !== undefined) el.setAttribute(attr, dict[key]);
        // keys para ARIA como "Anterior" / "Siguiente"
        if (dict[el.getAttribute(attr)]) el.setAttribute(attr, dict[el.getAttribute(attr)]);
      });
    } else if (dict[key] !== undefined) {
      el.textContent = dict[key];
    }
  });

  // HTML enriquecido (permite <strong>, <span>, etc.)
  document.querySelectorAll('[data-i18n-html]').forEach(el=>{
    const key = el.getAttribute('data-i18n-html');
    if (dict[key] !== undefined) el.innerHTML = dict[key];
  });

  // Title y meta description
  document.title = dict.title || document.title;
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc) metaDesc.setAttribute('content', dict.meta_description || metaDesc.getAttribute('content'));

  // ARIA labels de flechas y carrusel (si existen)
  const left = document.querySelector('.slider__arrow.left');
  const right = document.querySelector('.slider__arrow.right');
  const track = document.getElementById('sliderTrack');
  if (left) left.setAttribute('aria-label', dict["Anterior"] || "Anterior");
  if (right) right.setAttribute('aria-label', dict["Siguiente"] || "Siguiente");

  // <html lang="">
  document.documentElement.setAttribute('lang', lang);
}


