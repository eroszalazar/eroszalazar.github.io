// Inicializa idioma (preferencia guardada → navegador → 'es')
function initLang(){
  const saved = localStorage.getItem('lang');
  let lang = saved || (navigator.language || 'es').slice(0,2);
  if (!I18N[lang]) lang = 'es';
  applyI18N(lang);

  const btn = document.getElementById('langToggle');
  if (btn){
    btn.textContent = lang === 'es' ? 'EN' : 'ES';
    btn.addEventListener('click', ()=>{
      lang = (lang === 'es') ? 'en' : 'es';
      localStorage.setItem('lang', lang);
      btn.textContent = lang === 'es' ? 'EN' : 'ES';
      applyI18N(lang);
    });
  }
}
initLang();

// === NUEVO: Render de Cursos & Filtros ===
function currentLang(){ return (localStorage.getItem('lang') && I18N[localStorage.getItem('lang')]) ? localStorage.getItem('lang') : 'es'; }

function getAllSkills(courses){
  const set = new Set();
  courses.forEach(c => c.skills.forEach(s => set.add(s)));
  return Array.from(set).sort((a,b)=>a.localeCompare(b));
}

function courseTitle(course, lang){
  return (lang === 'en' ? course.title_en : course.title_es) || course.title_es || course.title_en;
}

function renderCourseCard(course, lang){
  const t = I18N[lang];
  const title = courseTitle(course, lang);
  const meta  = `${course.provider} • ${t.courses_meta_year || 'Año'} ${course.year} • ${course.hours}${t.courses_meta_hours || 'hs'}`;
  const skills = (course.skills || [])
    .map(s => `<span class="chip">${s}</span>`)
    .join('');

  // 👇 prioridad: link de LinkedIn / fallback al url de certificado / sino "#"
  const href = course.linkedin || course.url || "#";

  return `
    <a class="course-card"
       href="${href}"
       target="_blank"
       rel="noopener">
      <div class="course-card__title">${title}</div>
      <div class="course-card__meta">${meta}</div>
      <div class="course-card__skills">${skills}</div>
    </a>
  `;
}


function renderCoursesGrid(filterSkill = null){
  const grid = document.getElementById('coursesGrid');
  if (!grid) return;
  const lang = currentLang();
  const items = COURSES
    .filter(c => !filterSkill || c.skills.includes(filterSkill))
    .sort((a,b)=> (b.year - a.year) || (courseTitle(a,lang).localeCompare(courseTitle(b,lang)) * 1));
  grid.innerHTML = items.map(c => renderCourseCard(c, lang)).join('') || `<p>${lang==='es'?'Sin resultados.':'No results.'}</p>`;
}

function renderCourseFilters(){
  const wrap = document.getElementById('courseFilters');
  if (!wrap) return;
  const lang = currentLang();
  const t = I18N[lang];
  const skills = getAllSkills(COURSES);
  const buttons = [`<button class="chip" data-skill="">${t.courses_filter_all}</button>`]
    .concat(skills.map(s => `<button class="chip" data-skill="${s}">${s}</button>`));
  wrap.innerHTML = buttons.join('');

  wrap.addEventListener('click', (e)=>{
    const btn = e.target.closest('button[data-skill]');
    if (!btn) return;
    // estado activo
    wrap.querySelectorAll('button').forEach(b => b.classList.remove('active'));
    btn.classList.add('active');
    const skill = btn.getAttribute('data-skill') || null;
    renderCoursesGrid(skill);
  });

  // activar "Todos" por defecto
  const first = wrap.querySelector('button[data-skill=""]');
  if (first) first.classList.add('active');
}

function initCourses(){
  renderCourseFilters();
  renderCoursesGrid(null);
}

// re-render cuando cambie el idioma
function onLangChanged(){
  // Re-render cursos y filtros para que cambie el texto/meta
  renderCourseFilters();
  // Mantener filtro activo actual (si lo hubiera)
  const active = document.querySelector('#courseFilters button.active');
  const skill = active ? active.getAttribute('data-skill') || null : null;
  renderCoursesGrid(skill);
}

